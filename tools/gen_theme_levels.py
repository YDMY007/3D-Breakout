DIFF_NAMES = ['教学', '简单', '普通', '困难', '专家']


def is_multi(lv):
    return isinstance(lv[0], (list, tuple))


def as_layers(lv):
    return [list(l) for l in lv] if is_multi(lv) else [list(lv)]


def encode(name, lv, diff):
    """编码一关: byte0=难度, byte1-8=ASCII 名, 各层依序写入 n=0..。"""
    layers = as_layers(lv)
    assert 1 <= len(layers) <= QS, '%s: 层数 %d 越界' % (name, len(layers))
    buf = bytearray(BLOCK)
    buf[0] = diff
    nb = name[:8].encode('ascii')
    buf[1:1 + len(nb)] = nb
    for h, rows in enumerate(layers):
        assert len(rows) == PC, '%s L%d: 需要 %d 行' % (name, h, PC)
        for t in range(PC):
            line = rows[t]
            assert len(line) == BN, '%s L%d 行宽需 %d: %r' % (name, h, BN, line)
            for i in range(BN):
                ch = line[i]
                v = 1 if ch == 'X' else (2 if ch == '#' else 0)
                buf[9 + t * BN * QS + i * QS + h] = v
    return bytes(buf)


def verify(name, lv):
    """三条硬规则: 尺寸 / 支撑 / 墙上不悬砖 / 连通性。"""
    layers = as_layers(lv)
    # 支撑: h>=1 有方块的格, h-1 必须有方块
    for h in range(1, len(layers)):
        for t in range(PC):
            for i in range(BN):
                if layers[h][t][i] != '.' and layers[h - 1][t][i] == '.':
                    raise AssertionError('%s L%d (%d,%d) 悬空无支撑' % (name, h, i, t))
    # 墙上不悬砖: 每根柱最高墙的上方不得有可破坏砖
    for t in range(PC):
        for i in range(BN):
            wall_top = -1
            for h in range(len(layers)):
                if layers[h][t][i] == 'X':
                    wall_top = h
            if wall_top >= 0:
                for h in range(wall_top + 1, len(layers)):
                    if layers[h][t][i] == '#':
                        raise AssertionError('%s 柱(%d,%d): 墙上悬砖 L%d' % (name, i, t, h))
    # 连通性: 底层每个可破坏砖与边界经非墙格连通（4 邻接）
    base = layers[0]
    grid = [[1 if c == 'X' else 0 for c in ln] for ln in base]
    seen = [[False] * BN for _ in range(PC)]
    stack = []
    for t in range(PC):
        for i in range(BN):
            if t in (0, PC - 1) or i in (0, BN - 1):
                if grid[t][i] != 1 and not seen[t][i]:
                    seen[t][i] = True
                    stack.append((t, i))
    while stack:
        t, i = stack.pop()
        for dt, di in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            nt, ni = t + dt, i + di
            if 0 <= nt < PC and 0 <= ni < BN and not seen[nt][ni] and grid[nt][ni] != 1:
                seen[nt][ni] = True
                stack.append((nt, ni))
    for t in range(PC):
        for i in range(BN):
            if base[t][i] == '#' and not seen[t][i]:
                raise AssertionError('%s: 可破坏砖 (%d,%d) 被墙围死!' % (name, i, t))


def main():
    data = bytearray(open(SRC_DAT, 'rb').read())
    assert len(data) % BLOCK == 0
    themed = set(CN_NAMES.keys())

    # 剥掉旧主题关（按名字），保留 原版27 + 随机关15 + dzk5 = 47 关基座
    out = bytearray()
    kept, dropped = 0, 0
    for li in range(len(data) // BLOCK):
        base = li * BLOCK
        nm = data[base + 1:base + 9].split(b'\x00')[0].decode('ascii', 'replace')
        if nm in themed:
            dropped += 1
        else:
            out += data[base:base + BLOCK]
            kept += 1
    data = out
    print('base kept %d, old themed dropped %d' % (kept, dropped))
    assert kept == 47, '基座应为 47 关, 实际 %d' % kept

    existing = set()
    for li in range(len(data) // BLOCK):
        existing.add(data[li * BLOCK + 1:li * BLOCK + 9].split(b'\x00')[0].decode('ascii', 'replace'))

    total_new = 0
    for diff in range(5):
        levels = THEMES[diff]
        assert len(levels) == 10, 'diff %d has %d levels' % (diff, len(levels))
        for name, lv in levels:
            assert name not in existing, '重名: %s' % name
            assert len(name) <= 8 and name.isascii() and name == name.lower()
            assert name in CN_NAMES, '缺少中文名: %s' % name
            verify(name, lv)
            layers = as_layers(lv)
            bricks = sum(ln.count('#') for lay in layers for ln in lay)
            walls = sum(ln.count('X') for lay in layers for ln in lay)
            data += encode(name, lv, diff)
            existing.add(name)
            total_new += 1
            print('  [%s] %-8s %s: %d 层, %d 砖, %d 墙' % (
                DIFF_NAMES[diff], name, CN_NAMES[name], len(layers), bricks, walls))

    open(DST_DAT, 'wb').write(data)
    print('written %s: %d levels, %d bytes' % (DST_DAT, len(data) // BLOCK, len(data)))


